#!/usr/bin/env node
/**
 * Internal Linking Script for NexTool Blog
 * -----------------------------------------
 * 1. Scans all blog posts for title, keywords, meta description
 * 2. Clusters posts by topic similarity
 * 3. Adds "Related Articles" section to posts that don't have one
 * 4. Inserts before </body> (or before <footer if no </body>)
 */

const fs = require('fs');
const path = require('path');

const BLOG_DIR = path.join(__dirname, '..', 'blog');
const DRY_RUN = process.argv.includes('--dry-run');
const CLEAN = process.argv.includes('--clean');

// ============================================================
// STEP 1: Parse all blog posts
// ============================================================

function getAllPosts() {
  const files = fs.readdirSync(BLOG_DIR)
    .filter(f => f.endsWith('.html') && f !== 'index.html');

  const posts = [];

  for (const file of files) {
    const filePath = path.join(BLOG_DIR, file);
    const html = fs.readFileSync(filePath, 'utf8');

    // Extract title (remove " | ANIMA", " | ANIMA Blog", " | NexTool" suffix)
    const titleMatch = html.match(/<title>(.*?)<\/title>/s);
    let title = titleMatch ? titleMatch[1].trim() : file.replace('.html', '');
    title = title.replace(/\s*\|\s*(ANIMA Blog|ANIMA|NexTool)\s*$/, '');

    // Extract meta keywords
    const kwMatch = html.match(/<meta\s+name="keywords"\s+content="([^"]*?)"/i);
    const keywords = kwMatch ? kwMatch[1].toLowerCase().split(',').map(k => k.trim()) : [];

    // Extract meta description
    const descMatch = html.match(/<meta\s+name="description"\s+content="([^"]*?)"/i);
    const description = descMatch ? descMatch[1] : '';

    // Extract article section
    const sectionMatch = html.match(/<meta\s+property="article:section"\s+content="([^"]*?)"/i);
    const section = sectionMatch ? sectionMatch[1] : '';

    // Check if Related Articles already exists (but NOT our auto-generated ones)
    const hasAutoGenerated = /<!-- Related Articles \(auto-generated\) -->/.test(html);
    const hasRelated = /Related Articles/i.test(html) && !hasAutoGenerated;

    const slug = file.replace('.html', '');

    posts.push({
      file,
      filePath,
      slug,
      title,
      keywords,
      description: description.toLowerCase(),
      section,
      hasRelated,
      // Build a "bag of words" for similarity matching
      bow: buildBagOfWords(slug, title, keywords, description, section),
    });
  }

  return posts;
}

// ============================================================
// STEP 2: Topic categorization via keyword clustering
// ============================================================

const TOPIC_CLUSTERS = {
  'pdf': ['pdf', 'compress pdf', 'merge pdf', 'split pdf', 'pdf tools', 'pdf to word', 'word to pdf', 'convert pdf', 'images to pdf', 'excel to pdf'],
  'json': ['json', 'json formatter', 'json tools', 'json schema', 'json validation', 'jsonpath', 'json editor'],
  'css': ['css', 'flexbox', 'css grid', 'css animation', 'gradient', 'css layout', 'css tricks', 'css generators', 'tailwind', 'responsive design'],
  'api': ['api', 'rest api', 'api testing', 'api design', 'graphql', 'api rate limiting', 'api mock', 'trpc', 'api endpoints'],
  'docker': ['docker', 'docker compose', 'kubernetes', 'container'],
  'git': ['git', 'github', 'github actions', 'git workflow', 'git commands'],
  'security': ['security', 'password', 'jwt', 'http security', 'web security', 'encoding', 'hashing', 'privacy policy'],
  'ai-automation': ['chatbot', 'automation', 'ai agent', 'ai tools', 'n8n', 'automate', 'solopreneur', 'freelancer', 'consciousness', 'mcp'],
  'anima': ['anima-', 'anima framework', 'anima vs', 'consciousness'],
  'image': ['image', 'ocr', 'background removal', 'image optimization', 'svg', 'upscale', 'qr code'],
  'javascript': ['javascript', 'react', 'node.js', 'typescript', 'npm', 'hooks', 'array methods', 'webassembly'],
  'developer-tools': ['developer tools', 'productivity', 'regex', 'cron', 'markdown', 'yaml', 'text comparison', 'environment variables', 'data format'],
  'web-dev': ['web', 'website', 'landing page', 'responsive', 'accessibility', 'meta tags', 'core web vitals', 'color theory', 'html email', 'seo'],
  'database': ['sql', 'mongodb', 'csv', 'data processing', 'database'],
  'business': ['business', 'website mistakes', 'small business', 'revenue', 'customers', 'brand voice', 'content', 'speech to text', 'video'],
};

function buildBagOfWords(slug, title, keywords, description, section) {
  const words = new Set();

  // From slug
  slug.split('-').forEach(w => { if (w.length > 2) words.add(w.toLowerCase()); });

  // From title
  title.toLowerCase().split(/\W+/).forEach(w => { if (w.length > 2) words.add(w); });

  // From keywords
  keywords.forEach(k => {
    k.split(/\W+/).forEach(w => { if (w.length > 2) words.add(w); });
    words.add(k.trim()); // Also add full keyword phrase
  });

  // From description
  description.split(/\W+/).forEach(w => { if (w.length > 2) words.add(w); });

  // From section
  if (section) {
    section.toLowerCase().split(/\W+/).forEach(w => { if (w.length > 2) words.add(w); });
  }

  return words;
}

function getTopics(post) {
  const topics = [];
  // Use slug + title + section for topic detection (not description — too noisy)
  const text = ' ' + [post.slug, post.title.toLowerCase(), post.section.toLowerCase(), ...post.keywords].join(' ') + ' ';

  for (const [topic, clusterKeywords] of Object.entries(TOPIC_CLUSTERS)) {
    for (const kw of clusterKeywords) {
      // Word-boundary-aware matching for short keywords
      if (kw.length <= 3) {
        // Short keywords need word boundary
        const regex = new RegExp(`\\b${kw.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}\\b`, 'i');
        if (regex.test(text)) {
          topics.push(topic);
          break;
        }
      } else if (text.includes(kw)) {
        topics.push(topic);
        break;
      }
    }
  }

  return topics;
}

// ============================================================
// STEP 3: Similarity scoring
// ============================================================

function calculateSimilarity(postA, postB) {
  if (postA.slug === postB.slug) return 0;

  let score = 0;

  // Topic overlap (strongest signal — MUST share at least one topic for high score)
  const topicsA = getTopics(postA);
  const topicsB = getTopics(postB);
  const sharedTopics = topicsA.filter(t => topicsB.includes(t));
  score += sharedTopics.length * 15;

  // Penalty: if both have topics but share NONE, penalize heavily
  if (topicsA.length > 0 && topicsB.length > 0 && sharedTopics.length === 0) {
    score -= 10;
  }

  // Keyword overlap (strong signal)
  const kwA = new Set(postA.keywords);
  const kwB = new Set(postB.keywords);
  let kwOverlap = 0;
  for (const kw of kwA) {
    if (kwB.has(kw)) kwOverlap++;
    // Also check partial keyword overlap (e.g., "api testing" matches "api testing best practices")
    for (const kwb of kwB) {
      if (kw !== kwb && (kw.includes(kwb) || kwb.includes(kw))) kwOverlap += 0.5;
    }
  }
  score += kwOverlap * 5;

  // Bag-of-words overlap (weaker signal, but only meaningful words)
  const stopWords = new Set(['the', 'and', 'for', 'with', 'how', 'what', 'your', 'you', 'that', 'this',
    'are', 'from', 'can', 'will', 'not', 'all', 'has', 'have', 'been', 'was', 'were', 'but', 'they',
    'than', 'its', 'also', 'into', 'just', 'use', 'using', 'used', 'best', 'free', 'online', 'complete',
    'guide', 'every', 'need', 'needs', 'most', 'make', 'more', 'when', 'each', '2026', '2025']);
  let bowOverlap = 0;
  for (const word of postA.bow) {
    if (stopWords.has(word)) continue;
    if (postB.bow.has(word)) bowOverlap++;
  }
  // Normalize by meaningful words count
  const meaningfulA = [...postA.bow].filter(w => !stopWords.has(w)).length;
  const meaningfulB = [...postB.bow].filter(w => !stopWords.has(w)).length;
  const avgSize = (meaningfulA + meaningfulB) / 2;
  if (avgSize > 0) {
    score += (bowOverlap / avgSize) * 15;
  }

  // Section match
  if (postA.section && postA.section === postB.section) {
    score += 8;
  }

  // Slug word overlap (good signal — slug words are intentional)
  const slugStopWords = new Set(['the', 'and', 'for', 'with', 'how', 'best', 'free', 'complete', 'guide', 'online', '2026', '2025']);
  const slugWordsA = postA.slug.split('-').filter(w => w.length > 2 && !slugStopWords.has(w));
  const slugWordsB = postB.slug.split('-').filter(w => w.length > 2 && !slugStopWords.has(w));
  const slugOverlap = slugWordsA.filter(w => slugWordsB.includes(w)).length;
  score += slugOverlap * 4;

  return score;
}

function findRelatedPosts(post, allPosts, count = 4) {
  const scored = allPosts
    .filter(p => p.slug !== post.slug)
    .map(p => ({ post: p, score: calculateSimilarity(post, p) }))
    .sort((a, b) => b.score - a.score);

  // Take top results but ensure minimum score threshold
  return scored
    .filter(s => s.score > 3)
    .slice(0, count)
    .map(s => s.post);
}

// ============================================================
// STEP 4: Generate and insert Related Articles HTML
// ============================================================

function generateRelatedHTML(relatedPosts) {
  const items = relatedPosts.map(p =>
    `      <li style="margin-bottom:0.5rem;"><a href="/blog/${p.slug}.html" style="color:#00d4ff;text-decoration:none;font-size:0.95rem;line-height:1.5;transition:color 0.2s;" onmouseover="this.style.color='#66e5ff'" onmouseout="this.style.color='#00d4ff'">${escapeHtml(p.title)}</a></li>`
  ).join('\n');

  return `
    <!-- Related Articles (auto-generated) -->
    <section style="max-width:680px;margin:2rem auto;padding:1.5rem 1.5rem 1rem;border-top:1px solid rgba(255,255,255,0.1);">
      <h3 style="font-size:1.1rem;font-weight:700;color:#fff;margin-bottom:1rem;">Related Articles</h3>
      <ul style="list-style:none;padding:0;margin:0;">
${items}
      </ul>
    </section>`;
}

function escapeHtml(str) {
  // First decode any existing HTML entities to avoid double-encoding
  let decoded = str
    .replace(/&amp;/g, '&')
    .replace(/&lt;/g, '<')
    .replace(/&gt;/g, '>')
    .replace(/&quot;/g, '"')
    .replace(/&#39;/g, "'");
  // Then re-encode
  return decoded
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;');
}

function removeAutoGeneratedRelated(html) {
  // Remove our auto-generated related sections
  return html.replace(/\n?\s*<!-- Related Articles \(auto-generated\) -->[\s\S]*?<\/section>/g, '');
}

function insertRelatedSection(html, relatedHTML) {
  // Strategy: Insert before <footer or before </body>
  // Try <footer first (more specific)
  const footerIdx = html.indexOf('<footer');
  if (footerIdx !== -1) {
    return html.slice(0, footerIdx) + relatedHTML + '\n    ' + html.slice(footerIdx);
  }

  // Fallback: before </body>
  const bodyIdx = html.lastIndexOf('</body>');
  if (bodyIdx !== -1) {
    return html.slice(0, bodyIdx) + relatedHTML + '\n' + html.slice(bodyIdx);
  }

  // Last resort: append
  return html + relatedHTML;
}

// ============================================================
// MAIN
// ============================================================

function main() {
  console.log('=== NexTool Blog Internal Linking Script ===\n');

  const allPosts = getAllPosts();
  console.log(`Found ${allPosts.length} blog posts total`);

  const postsWithRelated = allPosts.filter(p => p.hasRelated);
  const postsWithoutRelated = allPosts.filter(p => !p.hasRelated);

  console.log(`  - ${postsWithRelated.length} already have Related Articles`);
  console.log(`  - ${postsWithoutRelated.length} need Related Articles\n`);

  if (DRY_RUN) {
    console.log('[DRY RUN MODE - no files will be modified]\n');
  }

  // Clean mode: remove all auto-generated sections first
  if (CLEAN) {
    console.log('[CLEAN MODE - removing all auto-generated Related Articles sections]\n');
    let cleaned = 0;
    for (const post of allPosts) {
      const html = fs.readFileSync(post.filePath, 'utf8');
      if (/<!-- Related Articles \(auto-generated\) -->/.test(html)) {
        const newHtml = removeAutoGeneratedRelated(html);
        fs.writeFileSync(post.filePath, newHtml, 'utf8');
        cleaned++;
      }
    }
    console.log(`  Cleaned ${cleaned} files\n`);
    // Re-read posts after cleaning
    const freshPosts = getAllPosts();
    postsWithoutRelated.length = 0;
    freshPosts.filter(p => !p.hasRelated).forEach(p => postsWithoutRelated.push(p));
    // Update allPosts reference for similarity
    allPosts.length = 0;
    freshPosts.forEach(p => allPosts.push(p));
    console.log(`  After cleaning: ${postsWithoutRelated.length} need Related Articles\n`);
  }

  let modified = 0;
  let skipped = 0;

  for (const post of postsWithoutRelated) {
    const related = findRelatedPosts(post, allPosts, 4);

    if (related.length < 2) {
      console.log(`  SKIP: ${post.file} (only ${related.length} related posts found)`);
      skipped++;
      continue;
    }

    const relatedHTML = generateRelatedHTML(related);

    if (DRY_RUN) {
      console.log(`  WOULD ADD to ${post.file}:`);
      related.forEach(r => console.log(`    -> ${r.title}`));
      modified++;
      continue;
    }

    const html = fs.readFileSync(post.filePath, 'utf8');
    const newHtml = insertRelatedSection(html, relatedHTML);
    fs.writeFileSync(post.filePath, newHtml, 'utf8');

    console.log(`  ADDED to ${post.file}:`);
    related.forEach(r => console.log(`    -> ${r.title}`));
    modified++;
  }

  console.log(`\n=== Summary ===`);
  console.log(`  Modified: ${modified}`);
  console.log(`  Skipped:  ${skipped}`);
  console.log(`  Already had Related: ${postsWithRelated.length}`);
  console.log(`  Total posts: ${allPosts.length}`);

  // Also output the topic mapping
  console.log(`\n=== Topic Mapping ===`);
  for (const post of allPosts) {
    const topics = getTopics(post);
    if (topics.length > 0) {
      console.log(`  ${post.slug}: [${topics.join(', ')}]`);
    }
  }
}

main();
